import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseLines, judge } from '../lib/judge.mjs';

const report = { issue: 7, items: [{ n: 1, id: 'i1', name: '하나' }, { n: 2, id: 'i2', name: '둘' }] };
const c = (body, login = 'me', author_association = 'OWNER') => ({ body, user: { login }, author_association });

test('parseLines — 잡담 · 전각 콜론 · 꼬리말', () => {
  const body = '1 채택\n2 기각: 너무 큼\n잡담입니다\n3 보류：Windows 정식판\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
  assert.deepEqual(parseLines(body), [
    { n: 1, verdict: '채택', reason: '' },
    { n: 2, verdict: '기각', reason: '너무 큼' },
    { n: 3, verdict: '보류', reason: 'Windows 정식판' },
  ]);
});

test('같은 번호는 마지막이 이기고, 없는 번호는 무시', () => {
  const r = judge(report, [c('1 채택', 'a'), c('1 기각: 바꿈\n9 채택', 'b')]);
  assert.equal(r.issue, 7);
  assert.deepEqual(r.judgments, [{ n: 1, id: 'i1', name: '하나', verdict: '기각', reason: '바꿈', by: 'b' }]);
  assert.equal(r.closable, false);
});

test('parseLines — 자연스러운 변형도 판정이다', () => {
  const body = '2 기각 너무 큼\n2 기각 - 너무 큼\n1. 채택\n1) 채택\n#1 채택\n1번 채택';
  assert.deepEqual(parseLines(body).map((j) => [j.n, j.verdict, j.reason]), [
    [2, '기각', '너무 큼'], [2, '기각', '너무 큼'], [1, '채택', ''], [1, '채택', ''], [1, '채택', ''], [1, '채택', ''],
  ]);
  assert.deepEqual(parseLines('1 채택함\n2026 기각된 것들\n---'), []);
});

test('숫자로 시작했지만 해석 못 한 줄은 unparsed 로 보여 준다', () => {
  const r = judge(report, [c('1 채택함\n잡담\n2 기각', 'a')]);
  assert.deepEqual(r.unparsed, [{ line: '1 채택함', by: 'a' }]);
  assert.deepEqual(r.judgments.map((j) => j.n), [2]);
});

test('closable — 채택이 남으면 열어 둔다', () => {
  assert.equal(judge(report, [c('1 도입\n2 기각')]).closable, true);
  assert.equal(judge(report, [c('1 채택\n2 기각')]).closable, false);
});

test('공개 저장소 — 소유자 · 멤버 · 협업자 댓글만 판정, 나머지는 ignored 로 보여 준다', () => {
  const r = judge(report, [c('1 채택', 'me'), c('1 기각\n2 기각', 'stranger', 'NONE'), c('2 보류: 나중', 'col', 'COLLABORATOR'), { body: '2 도입', user: { login: 'x' } }]);
  assert.deepEqual(r.judgments.map((j) => [j.n, j.verdict, j.by]), [[1, '채택', 'me'], [2, '보류', 'col']]);
  assert.deepEqual(r.ignored, ['stranger', 'x']);
});
